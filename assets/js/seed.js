import { imageFor, describe } from './seed-details.js';

const img = (name) => `assets/img/${name}.webp`;

// صنف: الاسم، الأسعار (سعر لكل حجم)، وخصائص اختيارية
const I = (name, prices, extra = {}) => ({ name, prices: [].concat(prices), ...extra });
// صنف سعره مشكوك فيه: يظهر «اسأل عن السعر» لحد ما يتأكد من الداشبورد
const ask = (name, prices, extra = {}) => I(name, prices, { ...extra, confirm: true });
const G = (name, sizes, items) => ({ name, sizes, items });

function category(id, order, name, image, groups) {
  let n = 0;
  return {
    id,
    order,
    name,
    image: img(image),
    groups: groups.map((g) => ({
      ...g,
      items: g.items.map((item) => ({
        id: `${id}-${++n}`,
        name: item.name,
        desc: item.desc || describe(id, item.name, g.name),
        prices: item.prices,
        image: img(item.image || imageFor(id, item.name)),
        soldOut: false,
        featured: Boolean(item.featured),
        confirm: Boolean(item.confirm),
      })),
    })),
  };
}

